import express from 'express';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = 3000;

app.use(express.json({ limit: '15mb' }));

// Server-side GoogleGenAI client
const apiKey = process.env.GEMINI_API_KEY;
const ai = new GoogleGenAI({
  apiKey,
  httpOptions: {
    headers: {
      'User-Agent': 'aistudio-build',
    },
  },
});

// 1. Text-to-Speech API using gemini-3.8-flash-tts
app.post('/api/tts', async (req, res) => {
  try {
    const { text, speaker = 'Puck', style = 'High-octane arcade race announcer' } = req.body;
    if (!text || typeof text !== 'string') {
      res.status(400).json({ error: 'Text prompt is required' });
      return;
    }

    if (!apiKey) {
      res.status(503).json({ error: 'GEMINI_API_KEY not configured on server' });
      return;
    }

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash-tts',
      contents: [
        {
          role: 'user',
          parts: [
            {
              text: text.slice(0, 300),
              speechMetadata: {
                style,
              },
            },
          ],
        },
      ],
      config: {
        responseModalities: ['AUDIO'],
        speechConfig: {
          voiceConfig: {
            // Voices: 'Puck', 'Charon', 'Kore', 'Fenrir', 'Zephyr'
            prebuiltVoiceConfig: { voiceName: speaker },
          },
        },
      },
    });

    const base64Audio = response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;
    if (!base64Audio) {
      res.status(500).json({ error: 'No audio generated by model' });
      return;
    }

    res.json({
      audio: base64Audio,
      mimeType: 'audio/wav',
    });
  } catch (err: any) {
    console.error('TTS Generation error:', err);
    res.status(500).json({ error: err.message || 'Failed to generate speech' });
  }
});

// 2. High-Quality Image Generation API using gemini-3-pro-image-preview
// Supports user affordance for image size: 1K, 2K, 4K
app.post('/api/generate-image', async (req, res) => {
  try {
    const { prompt, imageSize = '1K', aspectRatio = '16:9' } = req.body;
    if (!prompt) {
      res.status(400).json({ error: 'Prompt is required' });
      return;
    }

    if (!apiKey) {
      res.status(503).json({ error: 'GEMINI_API_KEY not configured on server' });
      return;
    }

    // Model specified by feature requirement: gemini-3-pro-image-preview
    // Valid size options: '1K', '2K', '4K'
    const validSizes = ['1K', '2K', '4K'];
    const selectedSize = validSizes.includes(imageSize) ? imageSize : '1K';

    const response = await ai.models.generateContent({
      model: 'gemini-3-pro-image-preview',
      contents: {
        parts: [
          {
            text: `Professional concept art of a high-speed motorcycle in Road Rash style: ${prompt}. Cinematic lighting, asphalt reflections, extreme detail. No UI, no text overlay.`,
          },
        ],
      },
      config: {
        imageConfig: {
          aspectRatio: aspectRatio as any,
          imageSize: selectedSize as any,
        },
      },
    });

    let imageUrl = '';
    const parts = response.candidates?.[0]?.content?.parts || [];
    for (const part of parts) {
      if (part.inlineData?.data) {
        imageUrl = `data:${part.inlineData.mimeType || 'image/png'};base64,${part.inlineData.data}`;
        break;
      }
    }

    if (!imageUrl) {
      res.status(500).json({ error: 'No image returned by model' });
      return;
    }

    res.json({
      imageUrl,
      imageSize: selectedSize,
      aspectRatio,
    });
  } catch (err: any) {
    console.error('Image Generation error:', err);
    res.status(500).json({ error: err.message || 'Failed to generate image' });
  }
});

// 3. Multi-turn Chatbot API
// Uses gemini-3.8-flash (default general), gemini-3.1-flash-lite (fast), or gemini-4-argon (complex)
app.post('/api/chat', async (req, res) => {
  try {
    const {
      messages = [],
      role = 'mechanic',
      model = 'gemini-3.8-flash',
    } = req.body;

    if (!apiKey) {
      res.status(503).json({ error: 'GEMINI_API_KEY not configured on server' });
      return;
    }

    // Role system instructions
    let systemInstruction = '';
    if (role === 'mechanic') {
      systemInstruction =
        '你是“老扳手”阿克塞尔（Axel "Wrench" McCoy），地下暴力摩托赛事的资深首席机械师。性格粗粝干练，说话带有润滑油和烈酒的硬汉味道。为玩家提供摩托车调校（发动机马力、转弯抓地力、刹车平衡、氮气增压）、改装武器（铁链、带刺球棒）的建议，以及应对不同AI难度赛车手的战术技巧。回复简洁有力，充满90年代街机硬核赛车风格。';
    } else if (role === 'police') {
      systemInstruction =
        '你是加州公路巡警“铁面”奥利里警长（Sergeant O’Leary）。你负责在高速公路上驾驶巡逻摩托围剿非法暴力飙车党。说话威严严厉，通过对讲机警告玩家立即靠边停车，否则将使用警棍并呼叫路障拦截。如果玩家向你挑衅，你会放狠话并宣布立刻对玩家进行高压追捕。';
    } else if (role === 'rival') {
      systemInstruction =
        '你是“毒蛇”维珀（Viper），公路暴走族“黑骷髅会”的王牌车手。性格狂妄狠辣，擅长甩动生锈铁链将对手扫下机车。你用讥讽和挑衅的语气与玩家对话，嘲讽玩家的低速驾驶，并就下一场比赛开出挑战赌局。';
    } else {
      systemInstruction =
        '你是狂飙暴力摩托地下赛事的赛事官方播报员与信息联络员，提供实时路况、对手情报和赛道技巧。';
    }

    // Ensure model selection aligns with available valid models
    let selectedModel = 'gemini-3.8-flash';
    if (model === 'gemini-4-argon' || model === 'gemini-3.1-flash-lite') {
      selectedModel = model;
    }

    // Convert messages into API format
    const contents = messages.map((m: { role: string; content: string }) => ({
      role: m.role === 'user' ? 'user' : 'model',
      parts: [{ text: m.content }],
    }));

    const response = await ai.models.generateContent({
      model: selectedModel,
      contents,
      config: {
        systemInstruction,
      },
    });

    const reply = response.text || '（发动机轰鸣声掩盖了声音...）';
    res.json({ reply, model: selectedModel });
  } catch (err: any) {
    console.error('Chat error:', err);
    res.status(500).json({ error: err.message || 'Failed to process chat message' });
  }
});

// Setup Vite in Dev or serve static in Prod
async function startServer() {
  if (process.env.NODE_ENV !== 'production') {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: {
        middlewareMode: true,
        hmr: false,
      },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Road Rash server running at http://0.0.0.0:${PORT}`);
  });
}

startServer();
